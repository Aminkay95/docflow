from __future__ import annotations

import os
from collections.abc import Generator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, create_engine, text
from sqlalchemy.engine import make_url

from tests.integration.conftest import _ensure_database

PROJECT_ROOT = Path(__file__).resolve().parents[2]
MIGRATION_DATABASE_URL = os.getenv(
    "MIGRATION_TEST_DATABASE_URL",
    "postgresql+psycopg://trade:trade@localhost:5432/trade_extract_migration_test",
)

pytestmark = pytest.mark.integration

TRIGGER_NAMES = {
    "trg_clients_updated_at",
    "trg_reviewers_updated_at",
    "trg_jobs_updated_at",
    "trg_segments_updated_at",
    "trg_documents_updated_at",
    "trg_job_tasks_updated_at",
}


def _config() -> Config:
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    config.set_main_option("prepend_sys_path", str(PROJECT_ROOT / "src"))
    config.set_main_option("sqlalchemy.url", MIGRATION_DATABASE_URL)
    return config


@pytest.fixture
def migration_engine() -> Generator[Engine, None, None]:
    try:
        _ensure_database(MIGRATION_DATABASE_URL)
        engine = create_engine(
            make_url(MIGRATION_DATABASE_URL).update_query_dict({"connect_timeout": "3"})
        )
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
    except Exception as exc:  # noqa: BLE001
        pytest.skip(f"PostgreSQL is not available at {MIGRATION_DATABASE_URL}: {exc}")
    yield engine
    engine.dispose()


def test_initial_migration_upgrades_and_downgrades_cleanly(migration_engine: Engine) -> None:
    config = _config()
    command.downgrade(config, "base")
    command.upgrade(config, "head")
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"models drift from the migrated DDL: {exc}")

    with migration_engine.connect() as connection:
        extension = connection.execute(
            text("SELECT 1 FROM pg_extension WHERE extname = 'btree_gist'")
        ).first()
        function = connection.execute(
            text("SELECT 1 FROM pg_proc WHERE proname = 'set_updated_at'")
        ).first()
        triggers = {
            row[0]
            for row in connection.execute(
                text(
                    "SELECT tgname FROM pg_trigger "
                    "WHERE NOT tgisinternal AND tgname LIKE 'trg_%_updated_at'"
                )
            )
        }
        constraint = connection.execute(
            text("SELECT 1 FROM pg_constraint WHERE conname = 'ex_segments_page_range'")
        ).first()
        tables = {
            row[0]
            for row in connection.execute(
                text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
            )
        }

    assert extension is not None, "btree_gist extension was not created"
    assert function is not None, "set_updated_at() was not created"
    assert triggers == TRIGGER_NAMES
    assert constraint is not None, "segments exclusion constraint was not created"
    for table in (
        "clients",
        "api_keys",
        "reviewers",
        "policies",
        "jobs",
        "submissions",
        "files",
        "segments",
        "documents",
        "job_tasks",
        "webhook_deliveries",
    ):
        assert table in tables

    command.downgrade(config, "base")

    with migration_engine.connect() as connection:
        remaining = {
            row[0]
            for row in connection.execute(
                text(
                    "SELECT tablename FROM pg_tables "
                    "WHERE schemaname = 'public' AND tablename <> 'alembic_version'"
                )
            )
        }
        function = connection.execute(
            text("SELECT 1 FROM pg_proc WHERE proname = 'set_updated_at'")
        ).first()

    assert remaining == set()
    assert function is None
